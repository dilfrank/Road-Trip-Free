const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {stripTypeScriptTypes}=require('node:module');
function load(file){let src=stripTypeScriptTypes(fs.readFileSync(file,'utf8'));const names=[...src.matchAll(/export (?:function|const) (\w+)/g)].map(m=>m[1]);return new Function(src.replace(/export /g,'')+`\nreturn {${names.join(',')}};`)();}
const p=load(path.resolve(__dirname,'../lib/planner.ts'));
const {chinaPlaces:places}=load(path.resolve(__dirname,'../data/chinaPlaces.ts'));
const t={...p.emptyTrip,origin:'成都',date:'2026-12-01',thought:'不想看海，很期待但也担心累',preferences:['文化'],needs:'同行者说不想爬台阶'};
assert.equal(p.understand(t).original,t.thought);
assert.deepEqual(p.understand(t).preferences,['文化']);
assert.equal(p.understand(t).confirmed,false);
assert.equal(p.makePlan(t,['chengdu'],places,false).status,'needs_input');
assert.equal(p.makePlan(t,[],places,true).status,'needs_input');
assert.deepEqual(p.makePlan(t,['missing'],places,true).missingIds,['missing']);
const plan=p.makePlan(t,['chengdu'],places,true);
assert.equal(plan.status,'provisional');
assert.equal(plan.days.length,3);
assert.equal(plan.days[0].stops[0],'成都');
assert.equal(plan.days.at(-1).stops.at(-1),'成都');
assert.ok(plan.issues.some(s=>s.includes(t.needs)));
assert.equal(p.makePlan({...t,days:1},['chengdu','yading'],places,true).status,'infeasible');
assert.equal(p.makePlan({...t,end:'重庆'},['chengdu'],places,true).days.at(-1).stops.at(-1),'重庆');
for(const days of [0,NaN,1.5,31])assert.equal(p.makePlan({...t,days},['chengdu'],places,true).status,'needs_input');
assert.equal(p.restoreTrip({}),null);
assert.ok(p.validateTrip({...t,date:'2026-02-31'}).length);
assert.equal(plan.days[0].stops.length,1);
assert.equal(p.restoreTrip({...t,preferences:['伪造偏好']}),null);
assert.deepEqual(p.restoreTrip(t),t);
assert.equal(p.findCandidates(places,{...p.understand(t),confirmed:true},'不存在').length,0);
assert.equal(p.findCandidates(places,{...p.understand(t),confirmed:true},'')[0].id,'chengdu');
assert.match(p.exportPlan(t,plan,[places[0]]),/待核实/);
assert.match(p.exportPlan(t,plan,[places[0]]),/S080/);
console.log('PASS: China planner intent fidelity, confirmation gate, single-place plan, return, unknowns, conflicts, invalid data, retrieval and export');
